"""Fluency benchmark: multilingual sentence-completion contexts for base models.

Dataset adapter for the packaged ``fluency`` task family. Contexts come from
``geoalgo/multilingual-fluency`` (generated by
``scripts/fluency/generate_fluency.py``), where each language is a separate
HF dataset config/folder; a task like ``fluency-mandarin-chinese`` selects the
``Mandarin Chinese`` folder through the task's language variants.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from huggingface_hub import snapshot_download

from judgearena.tasks.schema import HuggingFaceDatasetSource, ResolvedTaskSpec

FLUENCY_HF_REPO = "geoalgo/multilingual-fluency"

