"""Fluency benchmark: multilingual sentence-completion contexts for base models.

Loads per-language contexts from ``geoalgo/multilingual-fluency`` (the
successor to ``geoalgo/multilingual-contexts-to-be-completed``), which is
generated by ``scripts/fluency/generate_fluency.py``. Each language is a
separate HF dataset config/folder, so a task like ``fluency-mandarin-chinese``
resolves to the ``Mandarin Chinese`` config.

Mirrors ``judgearena/instruction_dataset/m_arenahard.py``: the whole dataset
repo is snapshot-downloaded (pinned via ``dataset_revisions``) and then
filtered locally to the requested language's parquet file(s).
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from huggingface_hub import snapshot_download

from judgearena.dataset_revisions import hf_revision

FLUENCY_TASK_PREFIX = "fluency-"

FLUENCY_HF_REPO = "geoalgo/multilingual-fluency"

# Full language names, matching the HF dataset config/folder names produced by
# scripts/fluency/generate_fluency.py (sorted by number of speakers by Claude).
FLUENCY_LANGUAGES: tuple[str, ...] = (
    "English",
    "Mandarin Chinese",
    "Hindi",
    "Spanish",
    "French",
    "Standard Arabic",
    "Bengali",
    "Russian",
    "Portuguese",
    "Indonesian",
    "Japanese",
    "German",
    "Turkish",
    "Italian",
    "Ukrainian",
    "Polish",
    "Romanian",
    "Dutch",
    "Greek",
    "Hungarian",
    "Czech",
    "Catalan",
    "Bulgarian",
    "Swedish",
    "Danish",
    "Finnish",
    "Slovak",
    "Norwegian",
    "Croatian",
    "Georgian",
    "Lithuanian",
    "Slovene",
    "Latvian",
    "Albanian",
    "Macedonian",
    "Estonian",
    "Basque",
    "Galician",
    "Bosnian",
    "Serbian",
    "Icelandic",
    "Maltese",
    "Irish",
)


def fluency_language_slug(language: str) -> str:
    """CLI-friendly slug for a language, e.g. "Mandarin Chinese" -> "mandarin-chinese"."""
    return language.lower().replace(" ", "-")


_SLUG_TO_LANGUAGE: dict[str, str] = {
    fluency_language_slug(language): language for language in FLUENCY_LANGUAGES
}


def fluency_task_name(language: str) -> str:
    """Build the ``--task`` value for a given language, e.g. "French" -> "fluency-french"."""
    return f"{FLUENCY_TASK_PREFIX}{fluency_language_slug(language)}"


def is_fluency_task(task: str) -> bool:
    return task.startswith(FLUENCY_TASK_PREFIX)


def resolve_fluency_language(task: str) -> str:
    """Map a ``fluency-{slug}`` task name to its dataset config/folder name."""
    if not is_fluency_task(task):
        raise ValueError(f"Not a fluency task: {task!r}")
    slug = task[len(FLUENCY_TASK_PREFIX) :]
    if slug not in _SLUG_TO_LANGUAGE:
        raise ValueError(
            f"Unknown fluency language {slug!r} from task {task!r}. "
            f"Known languages: {sorted(_SLUG_TO_LANGUAGE)}"
        )
    return _SLUG_TO_LANGUAGE[slug]


def _fluency_local_root(local_path: Path) -> Path:
    local_subdir = FLUENCY_HF_REPO.split("/", 1)[1]
    return local_path / local_subdir


def download_fluency_dataset(local_path: Path) -> Path:
    """Download every language config of the fluency dataset; return the local root."""
    root = _fluency_local_root(local_path)
    snapshot_download(
        repo_id=FLUENCY_HF_REPO,
        repo_type="dataset",
        allow_patterns="*",
        local_dir=root,
        force_download=False,
        revision=hf_revision(FLUENCY_HF_REPO),
    )
    return root


def load_fluency_contexts(local_path: Path, task: str) -> pd.Series:
    """Load the ``instruction`` contexts (sentence prefixes) for a fluency task."""
    language = resolve_fluency_language(task)
    root = download_fluency_dataset(local_path)
    matches = sorted((root / language).glob("*.parquet"))
    assert matches, f"No parquet found for language {language!r} under {root}."
    df = pd.concat([pd.read_parquet(path) for path in matches], ignore_index=True)
    return df.loc[:, "sentence"].rename("instruction")


